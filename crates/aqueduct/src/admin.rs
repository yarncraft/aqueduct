//! Admin cockpit: a tiny HTTP server (no framework) on `health_addr`.
//!
//! - `GET /`            dashboard (embedded HTML + Tailwind CSS at `/admin.css`)
//! - `GET /healthz`     `200 ok` while the process is up (liveness, container HEALTHCHECK)
//! - `GET /readyz`      `200` only while the pipeline is streaming, else `503` (readiness)
//! - `GET /metrics`     Prometheus text exposition
//! - `GET /api/metrics` JSON snapshot
//! - `GET /api/events`  recent events read back from Kafka (`?topic=<t>&limit=<n>`)
//! - `GET /api/stream`  Server-Sent Events, one snapshot per second
//!
//! If `admin_token` is configured, `/metrics` and `/api/*` require it as
//! `Authorization: Bearer <token>` or `?token=<token>`. The event inspector (which exposes row
//! data) reads from the Kafka topics the sink writes to and is only enabled when a token is configured.
//!
//! Defensive limits: request read timeout, a cap on concurrent connections and on SSE streams,
//! write timeouts, constant-time token comparison and standard security headers.

use std::collections::{BTreeMap, VecDeque};
use std::fmt::Write as _;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use aqueduct_core::{Metrics, Snapshot, State};
use aqueduct_sinks::KafkaInspector;
use serde_json::json;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};
use tokio::sync::Semaphore;
use tokio::time::timeout;

const DASHBOARD: &str = include_str!("admin.html");
/// Generated by `ui/build.sh` (Tailwind CSS); committed so the Docker build needs no Node/Tailwind.
const STYLES: &str = include_str!("admin.css");
const HISTORY_LEN: usize = 120;

const MAX_CONNECTIONS: usize = 64;
const MAX_STREAMS: usize = 16;
/// Identical inspector queries within this window share one Kafka read.
const INSPECT_CACHE: Duration = Duration::from_secs(2);
const READ_TIMEOUT: Duration = Duration::from_secs(5);
const WRITE_TIMEOUT: Duration = Duration::from_secs(10);

/// The dashboard only needs same-origin resources plus its own inline script/style.
const CSP: &str =
    "default-src 'none'; script-src 'unsafe-inline'; style-src 'self' 'unsafe-inline'; \
                   connect-src 'self'; img-src 'self' data:; base-uri 'none'; form-action 'none'; \
                   frame-ancestors 'none'";

pub struct Admin {
    metrics: Arc<Metrics>,
    token: Option<String>,
    /// Events/second, one sample per second, oldest first.
    history: Mutex<VecDeque<f64>>,
    /// Per table `[insert, update, delete, truncate]` events/second, aligned with `history`.
    detail: Mutex<BTreeMap<String, VecDeque<[u64; 4]>>>,
    streams: AtomicUsize,
    inspector: Option<KafkaInspector>,
    inspect_cache: tokio::sync::Mutex<Option<(Instant, String, String)>>,
}

impl Admin {
    pub fn new(
        metrics: Arc<Metrics>,
        token: Option<String>,
        inspector: Option<KafkaInspector>,
    ) -> Arc<Self> {
        Arc::new(Self {
            metrics,
            token: token.filter(|t| !t.is_empty()),
            history: Mutex::new(VecDeque::with_capacity(HISTORY_LEN)),
            detail: Mutex::new(BTreeMap::new()),
            streams: AtomicUsize::new(0),
            inspector,
            inspect_cache: tokio::sync::Mutex::new(None),
        })
    }

    /// Sample the throughput once a second.
    pub async fn sample_forever(self: Arc<Self>) {
        let mut tick = tokio::time::interval(Duration::from_secs(1));
        let mut last = self.metrics.events_total();
        let mut last_ops: BTreeMap<String, [u64; 4]> = BTreeMap::new();
        loop {
            tick.tick().await;
            let now = self.metrics.events_total();
            let ops = self.metrics.snapshot().table_ops;
            {
                let mut h = self.history.lock().unwrap();
                if h.len() == HISTORY_LEN {
                    h.pop_front();
                }
                h.push_back(now.saturating_sub(last) as f64);
                let len = h.len();
                let mut d = self.detail.lock().unwrap();
                for (t, c) in &ops {
                    let prev = last_ops.get(t).copied().unwrap_or_default();
                    let mut delta = [0u64; 4];
                    for i in 0..4 {
                        delta[i] = c[i].saturating_sub(prev[i]);
                    }
                    let series = d.entry(t.clone()).or_default();
                    // A table seen for the first time is zero-filled back to the window start.
                    while series.len() + 1 < len {
                        series.push_back([0; 4]);
                    }
                    series.push_back(delta);
                }
                for series in d.values_mut() {
                    while series.len() > HISTORY_LEN {
                        series.pop_front();
                    }
                }
            }
            last_ops = ops;
            last = now;
        }
    }

    fn payload(&self) -> String {
        let history: Vec<f64> = self.history.lock().unwrap().iter().copied().collect();
        let rate = history.last().copied().unwrap_or(0.0);
        let mut v = serde_json::to_value(self.metrics.snapshot()).unwrap_or_default();
        v["events_per_sec"] = json!(rate);
        v["history"] = json!(history);
        v["history_ops"] = json!(*self.detail.lock().unwrap());
        v["inspector"] = json!(self.inspector.is_some());
        v.to_string()
    }

    fn authorized(&self, req: &Request) -> bool {
        match &self.token {
            None => true,
            Some(t) => {
                // Evaluate both so timing does not reveal which source matched.
                let a = req.bearer.as_deref().is_some_and(|b| ct_eq(b, t));
                let b = req.query_token.as_deref().is_some_and(|q| ct_eq(q, t));
                a | b
            }
        }
    }
}

/// Constant-time string comparison (length is not secret here).
fn ct_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    a.iter().zip(b).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

struct Request {
    path: String,
    bearer: Option<String>,
    query_token: Option<String>,
    query: String,
}

fn parse(raw: &str) -> Option<Request> {
    let mut lines = raw.lines();
    let mut first = lines.next()?.split_whitespace();
    if first.next()? != "GET" {
        return None;
    }
    let target = first.next()?;
    let (path, query) = target.split_once('?').unwrap_or((target, ""));
    let query_token = query
        .split('&')
        .find_map(|kv| kv.strip_prefix("token="))
        .map(str::to_string);
    let bearer = lines.find_map(|l| {
        let (k, v) = l.split_once(':')?;
        k.eq_ignore_ascii_case("authorization")
            .then(|| v.trim().strip_prefix("Bearer ").map(str::to_string))
            .flatten()
    });
    Some(Request {
        path: path.to_string(),
        bearer,
        query_token,
        query: query.to_string(),
    })
}

async fn send(sock: &mut TcpStream, bytes: &[u8]) -> bool {
    matches!(
        timeout(WRITE_TIMEOUT, sock.write_all(bytes)).await,
        Ok(Ok(()))
    )
}

async fn respond_with(sock: &mut TcpStream, status: &str, ctype: &str, extra: &str, body: &str) {
    let head = format!(
        "HTTP/1.1 {status}\r\ncontent-type: {ctype}\r\ncontent-length: {}\r\ncache-control: no-store\r\n\
         x-content-type-options: nosniff\r\nx-frame-options: DENY\r\nreferrer-policy: no-referrer\r\n\
         {extra}connection: close\r\n\r\n",
        body.len()
    );
    if send(sock, head.as_bytes()).await {
        send(sock, body.as_bytes()).await;
    }
}

async fn respond(sock: &mut TcpStream, status: &str, ctype: &str, body: &str) {
    respond_with(sock, status, ctype, "", body).await
}

fn escape_label(v: &str) -> String {
    v.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}

fn metric(o: &mut String, name: &str, kind: &str, help: &str) {
    let _ = writeln!(o, "# HELP {name} {help}");
    let _ = writeln!(o, "# TYPE {name} {kind}");
}

/// Prometheus text exposition format (version 0.0.4).
fn prometheus(s: &Snapshot) -> String {
    let mut o = String::new();
    metric(
        &mut o,
        "aqueduct_events_total",
        "counter",
        "Events delivered to the sink, by operation.",
    );
    for (op, n) in [
        ("insert", s.inserts),
        ("update", s.updates),
        ("delete", s.deletes),
        ("truncate", s.truncates),
    ] {
        let _ = writeln!(o, "aqueduct_events_total{{op=\"{op}\"}} {n}");
    }
    metric(
        &mut o,
        "aqueduct_table_events_total",
        "counter",
        "Events delivered, by table.",
    );
    for (t, n) in &s.tables {
        let _ = writeln!(
            o,
            "aqueduct_table_events_total{{table=\"{}\"}} {n}",
            escape_label(t)
        );
    }
    metric(
        &mut o,
        "aqueduct_errors_total",
        "counter",
        "Pipeline errors.",
    );
    let _ = writeln!(o, "aqueduct_errors_total {}", s.errors);
    metric(
        &mut o,
        "aqueduct_state",
        "gauge",
        "1 for the current pipeline state.",
    );
    for st in [
        State::Starting,
        State::Streaming,
        State::Stopped,
        State::Failed,
    ] {
        let name = format!("{st:?}").to_lowercase();
        let _ = writeln!(
            o,
            "aqueduct_state{{state=\"{name}\"}} {}",
            u8::from(st == s.state)
        );
    }
    metric(
        &mut o,
        "aqueduct_uptime_seconds",
        "gauge",
        "Process uptime.",
    );
    let _ = writeln!(o, "aqueduct_uptime_seconds {}", s.uptime_secs);
    if let Some(lag) = s.lag_ms {
        metric(
            &mut o,
            "aqueduct_lag_seconds",
            "gauge",
            "Commit time to delivery time of the newest event.",
        );
        let _ = writeln!(o, "aqueduct_lag_seconds {}", lag.max(0) as f64 / 1000.0);
    }
    if let Some(ms) = s.last_event_unix_ms {
        metric(
            &mut o,
            "aqueduct_last_event_timestamp_seconds",
            "gauge",
            "When the newest event was delivered (Unix time).",
        );
        let _ = writeln!(
            o,
            "aqueduct_last_event_timestamp_seconds {}",
            ms as f64 / 1000.0
        );
    }
    metric(
        &mut o,
        "aqueduct_sink_latency_seconds",
        "gauge",
        "Sink delivery latency per event (mean, last, max).",
    );
    for (k, v) in [
        ("avg", s.sink_avg_ms),
        ("last", s.sink_last_ms),
        ("max", s.sink_max_ms),
    ] {
        let _ = writeln!(
            o,
            "aqueduct_sink_latency_seconds{{stat=\"{k}\"}} {}",
            v / 1000.0
        );
    }
    o
}

async fn handle(admin: Arc<Admin>, mut sock: TcpStream) {
    let mut buf = [0u8; 4096];
    let n = match timeout(READ_TIMEOUT, sock.read(&mut buf)).await {
        Ok(Ok(n)) if n > 0 => n,
        _ => return,
    };
    let Some(req) = parse(&String::from_utf8_lossy(&buf[..n])) else {
        return respond(
            &mut sock,
            "405 Method Not Allowed",
            "text/plain",
            "GET only",
        )
        .await;
    };
    match req.path.as_str() {
        "/" | "/index.html" => {
            let extra = format!("content-security-policy: {CSP}\r\n");
            respond_with(
                &mut sock,
                "200 OK",
                "text/html; charset=utf-8",
                &extra,
                DASHBOARD,
            )
            .await
        }
        "/admin.css" => respond(&mut sock, "200 OK", "text/css; charset=utf-8", STYLES).await,
        "/healthz" => respond(&mut sock, "200 OK", "text/plain", "ok").await,
        "/readyz" => {
            if admin.metrics.snapshot().state == State::Streaming {
                respond(&mut sock, "200 OK", "text/plain", "ready").await
            } else {
                respond(
                    &mut sock,
                    "503 Service Unavailable",
                    "text/plain",
                    "not streaming",
                )
                .await
            }
        }
        "/metrics" | "/api/metrics" | "/api/stream" | "/api/events" if !admin.authorized(&req) => {
            respond_with(
                &mut sock,
                "401 Unauthorized",
                "text/plain",
                "www-authenticate: Bearer\r\n",
                "token required",
            )
            .await
        }
        "/metrics" => {
            let body = prometheus(&admin.metrics.snapshot());
            respond(
                &mut sock,
                "200 OK",
                "text/plain; version=0.0.4; charset=utf-8",
                &body,
            )
            .await
        }
        "/api/metrics" => respond(&mut sock, "200 OK", "application/json", &admin.payload()).await,
        "/api/events" => {
            let Some(inspector) = &admin.inspector else {
                return respond(
                    &mut sock,
                    "403 Forbidden",
                    "application/json",
                    r#"{"error":"inspector disabled; set admin_token and inspector = true"}"#,
                )
                .await;
            };
            let param = |k: &str| {
                req.query
                    .split('&')
                    .find_map(|kv| kv.strip_prefix(k)?.strip_prefix('='))
            };
            let topic = param("topic").filter(|t| !t.is_empty());
            let limit = param("limit")
                .and_then(|v| v.parse::<usize>().ok())
                .unwrap_or(100);
            let key = format!("{}|{limit}", topic.unwrap_or(""));
            let mut cache = admin.inspect_cache.lock().await;
            if let Some((at, k, body)) = cache.as_ref() {
                if *k == key && at.elapsed() < INSPECT_CACHE {
                    return respond(&mut sock, "200 OK", "application/json", body).await;
                }
            }
            match inspector.inspect(topic, limit).await {
                Ok(found) => {
                    let body = serde_json::to_string(&found).unwrap_or_default();
                    respond(&mut sock, "200 OK", "application/json", &body).await;
                    *cache = Some((Instant::now(), key, body));
                }
                Err(e) => {
                    tracing::warn!(error = %e, "inspector read failed");
                    let body = json!({ "error": e.to_string() }).to_string();
                    respond(&mut sock, "502 Bad Gateway", "application/json", &body).await
                }
            }
        }
        "/api/stream" => {
            if admin.streams.fetch_add(1, Ordering::SeqCst) >= MAX_STREAMS {
                admin.streams.fetch_sub(1, Ordering::SeqCst);
                return respond(
                    &mut sock,
                    "503 Service Unavailable",
                    "text/plain",
                    "too many streams",
                )
                .await;
            }
            stream(&admin, &mut sock).await;
            admin.streams.fetch_sub(1, Ordering::SeqCst);
        }
        _ => respond(&mut sock, "404 Not Found", "text/plain", "not found").await,
    }
}

async fn stream(admin: &Admin, sock: &mut TcpStream) {
    let head = "HTTP/1.1 200 OK\r\ncontent-type: text/event-stream\r\ncache-control: no-store\r\n\
                x-content-type-options: nosniff\r\nconnection: keep-alive\r\n\r\n";
    if !send(sock, head.as_bytes()).await {
        return;
    }
    let mut tick = tokio::time::interval(Duration::from_secs(1));
    loop {
        tick.tick().await;
        let frame = format!("data: {}\n\n", admin.payload());
        if !send(sock, frame.as_bytes()).await {
            return;
        }
    }
}

pub async fn serve(listener: TcpListener, admin: Arc<Admin>) {
    let slots = Arc::new(Semaphore::new(MAX_CONNECTIONS));
    loop {
        let Ok((sock, _)) = listener.accept().await else {
            continue;
        };
        // Shed load instead of queueing: a flood cannot exhaust file descriptors or memory.
        let Ok(permit) = slots.clone().try_acquire_owned() else {
            drop(sock);
            continue;
        };
        let admin = admin.clone();
        tokio::spawn(async move {
            handle(admin, sock).await;
            drop(permit);
        });
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every element the dashboard script looks up by id must exist in the HTML,
    /// otherwise the script throws on load and every handler after it is dead.
    #[test]
    fn dashboard_script_ids_exist_in_html() {
        let ids = |prefix: &str, suffix: &str| -> Vec<&str> {
            DASHBOARD
                .split(prefix)
                .skip(1)
                .filter_map(|r| r.split(suffix).next())
                .collect()
        };
        let defined = ids("id=\"", "\"");
        let mut missing: Vec<&str> = ids("$('", "')")
            .into_iter()
            .chain(ids("getElementById('", "')"))
            .filter(|id| !defined.contains(id))
            .collect();
        missing.sort_unstable();
        missing.dedup();
        assert!(missing.is_empty(), "ids used by script but absent from admin.html: {missing:?}");
        assert_eq!(DASHBOARD.matches("class=\"rateop").count(), 4, "one checkbox per op");
    }


    #[test]
    fn parses_token_from_query_and_header() {
        let r = parse("GET /api/stream?x=1&token=abc HTTP/1.1\r\nhost: a\r\n\r\n").unwrap();
        assert_eq!(
            (r.path.as_str(), r.query_token.as_deref()),
            ("/api/stream", Some("abc"))
        );
        let r = parse("GET /api/metrics HTTP/1.1\r\nAuthorization: Bearer s3\r\n\r\n").unwrap();
        assert_eq!(r.bearer.as_deref(), Some("s3"));
        assert!(parse("POST / HTTP/1.1\r\n\r\n").is_none());
    }

    #[test]
    fn token_gate() {
        let m = Arc::new(Metrics::new());
        let open = Admin::new(m.clone(), None, None);
        let locked = Admin::new(m, Some("k".into()), None);
        let anon = parse("GET /api/metrics HTTP/1.1\r\n\r\n").unwrap();
        let ok = parse("GET /api/metrics?token=k HTTP/1.1\r\n\r\n").unwrap();
        let bad = parse("GET /api/metrics?token=kk HTTP/1.1\r\n\r\n").unwrap();
        assert!(open.authorized(&anon));
        assert!(!locked.authorized(&anon));
        assert!(!locked.authorized(&bad));
        assert!(locked.authorized(&ok));
    }

    #[test]
    fn constant_time_eq() {
        assert!(ct_eq("abc", "abc"));
        assert!(!ct_eq("abc", "abd"));
        assert!(!ct_eq("abc", "abcd"));
        assert!(ct_eq("", ""));
    }

    #[test]
    fn prometheus_output() {
        let m = Metrics::new();
        let s = m.snapshot();
        let out = prometheus(&s);
        assert!(out.contains("aqueduct_events_total{op=\"insert\"} 0"));
        assert!(out.contains("aqueduct_state{state=\"starting\"} 1"));
        assert!(out.contains("aqueduct_errors_total 0"));
        assert_eq!(escape_label("a\"b\\c\nd"), "a\\\"b\\\\c\\nd");
    }

    async fn get(addr: std::net::SocketAddr, path: &str) -> String {
        let mut c = TcpStream::connect(addr).await.unwrap();
        c.write_all(format!("GET {path} HTTP/1.1\r\nhost: x\r\n\r\n").as_bytes())
            .await
            .unwrap();
        let mut out = String::new();
        c.read_to_string(&mut out).await.unwrap();
        out
    }

    async fn start(token: Option<&str>) -> std::net::SocketAddr {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        let metrics = Arc::new(Metrics::new());
        let admin = Admin::new(metrics, token.map(str::to_string), None);
        tokio::spawn(serve(listener, admin));
        addr
    }

    #[tokio::test]
    async fn serves_dashboard_health_and_metrics() {
        let addr = start(Some("k")).await;
        let page = get(addr, "/").await;
        assert!(page.contains("Stream operations"));
        assert!(page.contains("content-security-policy"));
        assert!(page.contains("x-frame-options: DENY"));
        assert!(get(addr, "/admin.css").await.contains("text/css"));
        assert!(get(addr, "/healthz").await.ends_with("ok"));
        assert!(get(addr, "/readyz").await.starts_with("HTTP/1.1 503"));
        assert!(get(addr, "/api/metrics").await.starts_with("HTTP/1.1 401"));
        assert!(get(addr, "/metrics").await.starts_with("HTTP/1.1 401"));
        let ok = get(addr, "/api/metrics?token=k").await;
        assert!(ok.starts_with("HTTP/1.1 200") && ok.contains("\"events_total\":0"));
        assert!(ok.contains("\"inspector\":false"));
        let prom = get(addr, "/metrics?token=k").await;
        assert!(prom.contains("aqueduct_events_total{op=\"insert\"} 0"));
        assert!(get(addr, "/api/events").await.starts_with("HTTP/1.1 401"));
    }

    #[tokio::test]
    async fn inspector_is_disabled_without_kafka_inspector() {
        let addr = start(Some("k")).await;
        let r = get(addr, "/api/events?token=k").await;
        assert!(r.starts_with("HTTP/1.1 403"));
    }
}
