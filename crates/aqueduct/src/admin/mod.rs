pub struct Admin {
    metrics: Arc<Metrics>,
    token: Option<String>,
    /// Events/second, one sample per second, oldest first.
    history: Mutex<VecDeque<f64>>,
    /// Per table `[insert, update, delete, truncate, read]` events/second, aligned with `history`.
    detail: Mutex<BTreeMap<String, VecDeque<[u64; OP_SLOTS]>>>,
    streams: AtomicUsize,
    inspector: Option<KafkaInspector>,
    /// The last inspector answer: when, for which query, the body. A std lock: never held
    /// across an await.
    inspect_cache: Mutex<Option<(Instant, String, String)>>,
    /// Lets one inspector read run at a time; the others wait (bounded by [`INSPECT_TIMEOUT`])
    /// and reuse its result when they asked the same.
    inspect_gate: tokio::sync::Mutex<()>,
    /// The host part of `health_addr`, also accepted as `Host` when there is no token.
    health_host: OnceLock<String>,
    /// Where snapshot requests go; unset for a source without snapshots.
    snapshots: OnceLock<SnapshotSender>,
    /// The sink's route plan: names each table's topic, and its counters (shared with the
    /// sink) feed `/api/routes` and the per-route metrics.
    router: OnceLock<RoutePlan>,
    /// Records the sink got acknowledged per topic (shared with the sink).
    topic_stats: OnceLock<Arc<TopicStats>>,
    /// Per-route and per-topic rates, sampled on the same tick as `history`.
    rates: Mutex<RateHistory>,
    /// The top tiles' per-minute means over the last hour, sampled on the same tick as `history`.
    kpis: Mutex<KpiHistory>,
    /// The last read of the Kafka offsets. A std lock: never held across an await.
    hwm_cache: Mutex<Option<HwmRead>>,
    /// Lets one request at a time read the offsets; the others wait and reuse its result.
    hwm_gate: tokio::sync::Mutex<()>,
}

/// High-water mark per partition, by topic.
type Offsets = BTreeMap<String, Vec<(i32, i64)>>;

struct HwmRead {
    at: Instant,
    topics: Vec<String>,
    result: Result<Offsets, String>,
}

impl Admin {
    pub fn new(
        metrics: Arc<Metrics>,
        token: Option<String>,
        inspector: Option<KafkaInspector>,
    ) -> Arc<Self> {
        Arc::new(Self {
            metrics,
            token: token.filter(|t| !t.is_empty()),
            history: Mutex::new(VecDeque::with_capacity(HISTORY_LEN)),
            detail: Mutex::new(BTreeMap::new()),
            streams: AtomicUsize::new(0),
            inspector,
            inspect_cache: Mutex::new(None),
            inspect_gate: tokio::sync::Mutex::new(()),
            health_host: OnceLock::new(),
            snapshots: OnceLock::new(),
            router: OnceLock::new(),
            topic_stats: OnceLock::new(),
            rates: Mutex::new(RateHistory::new(HISTORY_LEN)),
            kpis: Mutex::new(KpiHistory::new(HISTORY_LEN)),
            hwm_cache: Mutex::new(None),
            hwm_gate: tokio::sync::Mutex::new(()),
        })
    }

    /// The sink's route plan: names each table's topic on `/api/tables`, and describes the routes
    /// with their live counts on `/api/routes`, `/api/metrics` and `/metrics`.
    pub fn set_router(&self, router: RoutePlan) {
        let _ = self.router.set(router);
    }

    /// The sink's per-topic counters, for the Routing card's topic rates and `/metrics`.
    pub fn set_topic_stats(&self, stats: Arc<TopicStats>) {
        let _ = self.topic_stats.set(stats);
    }

    fn topic_bytes(&self) -> BTreeMap<String, u64> {
        self.topic_stats
            .get()
            .map(|s| s.bytes_snapshot())
            .unwrap_or_default()
    }

    fn topic_counts(&self) -> BTreeMap<String, OpCounts> {
        self.topic_stats
            .get()
            .map(|s| s.snapshot())
            .unwrap_or_default()
    }

    /// A read of the offsets of `topics` younger than [`HWM_CACHE`], if there is one.
    fn cached_hwms(&self, topics: &[String]) -> Option<(Instant, Result<Offsets, String>)> {
        let c = lock(&self.hwm_cache);
        let c = c.as_ref()?;
        (c.at.elapsed() < HWM_CACHE && c.topics == topics).then(|| (c.at, c.result.clone()))
    }

    /// The Kafka high-water marks of `topics` and when they were read, or `None` without an
    /// inspector. Bounded by [`HWM_TIMEOUT`], so a Kafka outage slows `/api/tables` down but
    /// never blocks it, and the cache lock is never held while Kafka is read.
    async fn kafka_hwms(&self, topics: &[String]) -> Option<(Instant, Result<Offsets, String>)> {
        let inspector = self.inspector.as_ref()?;
        if let Some(hit) = self.cached_hwms(topics) {
            return Some(hit);
        }
        let began = Instant::now();
        let read = timeout(HWM_TIMEOUT, async {
            let _gate = self.hwm_gate.lock().await;
            // Another request may have read them while this one waited.
            if let Some(hit) = self.cached_hwms(topics) {
                return hit;
            }
            let read = inspector.high_water_marks(topics).await.map_err(|e| {
                tracing::warn!(error = %e, "reading kafka offsets failed");
                e.to_string()
            });
            (Instant::now(), read)
        })
        .await
        .unwrap_or_else(|_| {
            let msg = format!("Kafka did not answer within {} s", HWM_TIMEOUT.as_secs());
            tracing::warn!("reading kafka offsets failed: {msg}");
            (Instant::now(), Err(msg))
        });
        let mut c = lock(&self.hwm_cache);
        // Keep a read that finished after this one started.
        if c.as_ref().is_none_or(|c| c.at < began) {
            *c = Some(HwmRead {
                at: read.0,
                topics: topics.to_vec(),
                result: read.1.clone(),
            });
        }
        Some(read)
    }

    /// `/api/tables`: per table, the newest delivered change and its topic's Kafka offsets.
    async fn tables_payload(&self) -> String {
        let snap = self.metrics.snapshot();
        let topic_of: BTreeMap<&str, Option<String>> = snap
            .table_marks
            .iter()
            .map(|(name, m)| {
                let topic = self
                    .router
                    .get()
                    .and_then(|r| r.topic_for(&m.schema, &m.table));
                (name.as_str(), topic)
            })
            .collect();
        let mut topics: Vec<String> = topic_of
            .values()
            .flatten()
            .filter(|t| !per_event_topic(t))
            .cloned()
            .collect();
        topics.sort();
        topics.dedup();
        let hwms = if topics.is_empty() {
            None
        } else {
            self.kafka_hwms(&topics).await
        };
        let tables: Vec<serde_json::Value> = snap
            .table_marks
            .iter()
            .map(|(name, m)| {
                let ops = snap.table_ops.get(name).copied().unwrap_or_default();
                let topic = topic_of.get(name.as_str()).cloned().flatten();
                let (kafka, error) = kafka_entry(&hwms, topic.as_deref(), &topic_of);
                let mut row = json!({
                    "table": name,
                    "topic": topic,
                    "events": snap.tables.get(name).copied().unwrap_or_default(),
                    "ops": { "c": ops[0], "u": ops[1], "d": ops[2], "t": ops[3], "r": ops[4] },
                    "last_lsn": m.last_lsn,
                    "last_commit_ms": m.last_commit_ms,
                    "last_delivered_ms": m.last_delivered_ms,
                    "kafka": kafka,
                });
                if let Some(e) = error {
                    row["error"] = json!(e);
                }
                row
            })
            .collect();
        // When the offsets shown were read, as Unix ms.
        let read_ms = hwms
            .as_ref()
            .map(|(at, _)| unix_ms().saturating_sub(at.elapsed().as_millis() as u64));
        json!({
            "state": snap.state,
            "checkpoint": snap.checkpoint,
            "inspector": self.inspector.is_some(),
            "kafka_read_ms": read_ms,
            "tables": tables,
        })
        .to_string()
    }

    /// Route `/api/snapshot` requests to the source.
    pub fn set_snapshots(&self, tx: SnapshotSender) {
        let _ = self.snapshots.set(tx);
    }

    fn route_counts(&self) -> Vec<RouteCount> {
        self.router
            .get()
            .map(|p| p.stats().snapshot())
            .unwrap_or_default()
    }

    /// Key, value and header bytes Kafka acknowledged since start.
    fn kafka_bytes(&self) -> u64 {
        self.topic_stats.get().map_or(0, |s| s.bytes())
    }

    /// The whole `/metrics` body. The OTLP exporter (`telemetry.rs`) reads the same text, so
    /// both carry the same series.
    pub fn exposition(&self) -> String {
        let mut body = prometheus(&self.metrics.snapshot());
        route_metrics(&mut body, &self.route_counts());
        topic_metrics(&mut body, &self.topic_counts());
        if self.topic_stats.get().is_some() {
            metric(
                &mut body,
                "aqueduct_kafka_bytes_total",
                "counter",
                "Key, value and header bytes of the records Kafka acknowledged.",
            );
            let _ = writeln!(body, "aqueduct_kafka_bytes_total {}", self.kafka_bytes());
        }
        body
    }

    /// Sample the throughput once a second. A tick that is late (a stalled runtime) is not
    /// made up with a burst of back-to-back ticks, which would read as a dip to zero and then
    /// a spike: the next tick waits a full second, and its rates are divided by the time that
    /// really passed.
    pub async fn sample_forever(self: Arc<Self>) {
        let period = Duration::from_millis(SAMPLE_MS);
        let mut tick = tokio::time::interval(period);
        tick.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
        let mut last = self.metrics.events_total();
        let mut last_bytes = self.kafka_bytes();
        let mut last_ops: BTreeMap<String, [u64; OP_SLOTS]> = BTreeMap::new();
        let mut last_at = Instant::now();
        loop {
            tick.tick().await;
            // At least a period: only the first tick, which fires at once, is ever early.
            let elapsed = last_at.elapsed().max(period);
            last_at = Instant::now();
            self.metrics.sample_source_lag();
            let now = self.metrics.events_total();
            let snap = self.metrics.snapshot();
            let rate = per_sec(now.saturating_sub(last), elapsed);
            let bytes = self.kafka_bytes();
            let bytes_rate = per_sec(bytes.saturating_sub(last_bytes), elapsed);
            self.record_sample(rate, &snap.table_ops, &last_ops);
            lock(&self.rates).record(
                &self.route_counts(),
                &self.topic_counts(),
                &self.topic_bytes(),
            );
            let usage = kpis::process_usage();
            lock(&self.kpis).record(unix_ms(), rate, bytes_rate, &snap, usage);
            last_ops = snap.table_ops;
            last = now;
            last_bytes = bytes;
        }
    }

    /// Adds one second's sample: the total rate and the per-table per-op deltas since `last_ops`.
    fn record_sample(
        &self,
        rate: f64,
        ops: &BTreeMap<String, [u64; OP_SLOTS]>,
        last_ops: &BTreeMap<String, [u64; OP_SLOTS]>,
    ) {
        let mut h = lock(&self.history);
        if h.len() == HISTORY_LEN {
            h.pop_front();
        }
        h.push_back(rate);
        let len = h.len();
        let mut d = lock(&self.detail);
        for (t, c) in ops {
            let prev = last_ops.get(t).copied().unwrap_or_default();
            let mut delta = [0u64; OP_SLOTS];
            for (i, slot) in delta.iter_mut().enumerate() {
                *slot = c[i].saturating_sub(prev[i]);
            }
            let series = d.entry(t.clone()).or_default();
            // A table seen for the first time is zero-filled back to the window start.
            while series.len() + 1 < len {
                series.push_back([0; OP_SLOTS]);
            }
            series.push_back(delta);
        }
        for series in d.values_mut() {
            while series.len() > HISTORY_LEN {
                series.pop_front();
            }
        }
    }

    fn payload(&self) -> String {
        let history: Vec<f64> = lock(&self.history).iter().copied().collect();
        let rate = history.last().copied().unwrap_or(0.0);
        let mut v = serde_json::to_value(self.metrics.snapshot()).unwrap_or_default();
        v["events_per_sec"] = json!(rate);
        v["history"] = json!(history);
        v["history_ops"] = json!(*lock(&self.detail));
        v["kafka_bytes_total"] = json!(self.kafka_bytes());
        v["kpis"] = lock(&self.kpis).window();
        v["inspector"] = json!(self.inspector.is_some());
        v["routes"] = json!(self.route_counts());
        v["rates"] = lock(&self.rates).latest();
        v.to_string()
    }

    fn authorized(&self, req: &Request) -> bool {
        match &self.token {
            None => true,
            Some(t) => req.bearer.as_deref().is_some_and(|b| ct_eq(b, t)),
        }
    }

    /// The `health_addr` the server is bound to: its host is accepted as `Host` without a token.
    pub fn set_health_addr(&self, addr: &str) {
        let _ = self.health_host.set(host_name(addr).to_string());
    }

    /// Without a token, refuse what a web page in the operator's browser could send to a
    /// protected route: a `Host` naming another site (DNS rebinding, which would let the page
    /// read `/api/*`), an `Origin` other than this server's, and a `POST` a cross-site form or
    /// no-cors `fetch` can send, which cannot be `application/json`. A `DELETE` from another
    /// origin needs a CORS preflight this server never grants. With a token none of this is
    /// needed: a page cannot attach it. The status and the reason when refused.
    fn browser_check(&self, req: &Request) -> Result<(), (StatusCode, &'static str)> {
        if self.token.is_some() {
            return Ok(());
        }
        if req.host.as_deref().is_some_and(|h| !self.allowed_host(h)) {
            return Err((
                StatusCode::FORBIDDEN,
                "Host not allowed without admin_token: open the cockpit by IP address or \
                 localhost, or set admin_token",
            ));
        }
        if req
            .origin
            .as_deref()
            .is_some_and(|o| !same_origin(o, req.host.as_deref()))
        {
            return Err((StatusCode::FORBIDDEN, "cross-origin request refused"));
        }
        if req.method == "POST" && !req.content_type.as_deref().is_some_and(is_json) {
            return Err((
                StatusCode::UNSUPPORTED_MEDIA_TYPE,
                "send the body as Content-Type: application/json",
            ));
        }
        Ok(())
    }

    /// A `Host` a rebinding attack cannot produce: an IP address (the attack needs a name it
    /// controls), `localhost`, or the host of `health_addr`.
    fn allowed_host(&self, host: &str) -> bool {
        let name = host_name(host);
        let name = name
            .strip_prefix('[')
            .and_then(|n| n.strip_suffix(']'))
            .unwrap_or(name);
        name.parse::<std::net::IpAddr>().is_ok()
            || name.eq_ignore_ascii_case("localhost")
            || self
                .health_host
                .get()
                .is_some_and(|h| !h.is_empty() && name.eq_ignore_ascii_case(h))
    }

    /// The `/api/events` answer: the inspection as JSON, or why there is none. Bounded by
    /// [`INSPECT_TIMEOUT`], and the cache lock is never held while Kafka is read, so a stalled
    /// broker slows the inspector down but never queues the server behind it.
    async fn inspect_events(
        &self,
        inspector: &KafkaInspector,
        topic: Option<&str>,
        limit: usize,
    ) -> (StatusCode, String) {
        let key = format!("{}|{limit}", topic.unwrap_or(""));
        let cached = || {
            lock(&self.inspect_cache)
                .as_ref()
                .filter(|(at, k, _)| *k == key && at.elapsed() < INSPECT_CACHE)
                .map(|(_, _, body)| body.clone())
        };
        if let Some(body) = cached() {
            return (StatusCode::OK, body);
        }
        let read = timeout(INSPECT_TIMEOUT, async {
            let _gate = self.inspect_gate.lock().await;
            // Another request may have read the same while this one waited.
            if let Some(body) = cached() {
                return Ok(body);
            }
            let found = inspector.inspect(topic, limit).await?;
            let body = serde_json::to_string(&found).unwrap_or_default();
            *lock(&self.inspect_cache) = Some((Instant::now(), key.clone(), body.clone()));
            Ok::<_, aqueduct_core::Error>(body)
        })
        .await;
        match read {
            Ok(Ok(body)) => (StatusCode::OK, body),
            Ok(Err(e)) => {
                tracing::warn!(error = %e, "inspector read failed");
                (
                    StatusCode::BAD_GATEWAY,
                    json!({ "error": e.to_string() }).to_string(),
                )
            }
            Err(_) => {
                let msg = format!(
                    "Kafka did not answer within {} s",
                    INSPECT_TIMEOUT.as_secs()
                );
                tracing::warn!("inspector read failed: {msg}");
                (
                    StatusCode::GATEWAY_TIMEOUT,
                    json!({ "error": msg }).to_string(),
                )
            }
        }
    }
}

/// `n` counted over `elapsed`, per second.
fn per_sec(n: u64, elapsed: Duration) -> f64 {
    n as f64 / elapsed.as_secs_f64()
}

/// Now, as Unix ms.
fn unix_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_millis() as u64)
}

/// The Tables card's note for a table whose topic comes from row content: there is no one topic
/// to read offsets from, and the Routing card shows the route.
const CONTENT_ROUTED: &str = "content-routed (see Routing)";

/// True for a topic that still has placeholders after `{schema}`/`{table}` are filled: it is
/// chosen per event (`{op}`, row fields). Kafka topic names cannot contain `{`.
fn per_event_topic(topic: &str) -> bool {
    topic.contains('{')
}

/// One table's `kafka` block on `/api/tables`, or why there is none. `topic_of` maps every
/// table to its topic, to count the tables that share it.
fn kafka_entry(
    hwms: &Option<(Instant, Result<Offsets, String>)>,
    topic: Option<&str>,
    topic_of: &BTreeMap<&str, Option<String>>,
) -> (Option<serde_json::Value>, Option<String>) {
    if topic.is_some_and(per_event_topic) {
        return (None, Some(CONTENT_ROUTED.into()));
    }
    let Some((_, read)) = hwms else {
        return (
            None,
            Some("Kafka offsets need the inspector: set admin_token and inspector = true".into()),
        );
    };
    let Some(topic) = topic else {
        return (None, Some("no route sends this table to a topic".into()));
    };
    let parts = match read {
        Err(e) => return (None, Some(e.clone())),
        Ok(found) => match found.get(topic) {
            Some(p) => p,
            None => return (None, Some(format!("topic {topic} not found in Kafka"))),
        },
    };
    let sharing = topic_of
        .values()
        .filter(|t| t.as_deref() == Some(topic))
        .count();
    let block = json!({
        "hwm_total": parts.iter().map(|p| p.1).sum::<i64>(),
        "partitions": parts
            .iter()
            .map(|(p, h)| json!({ "partition": p, "hwm": h }))
            .collect::<Vec<_>>(),
        "tables_on_topic": sharing,
    });
    (Some(block), None)
}
