/// The sampled history is best-effort telemetry: a panic that poisoned a lock must not take the
/// cockpit down, so recover the guard instead of unwrapping.
fn lock<T>(m: &Mutex<T>) -> MutexGuard<'_, T> {
    m.lock().unwrap_or_else(std::sync::PoisonError::into_inner)
}

