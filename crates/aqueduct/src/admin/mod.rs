//! Admin cockpit: a small HTTP/1.1 server on `health_addr`, built on hyper (`server.rs`), with
//! the routes in `api.rs` and the Prometheus exposition in `prometheus.rs`.
//!
//! - `GET /`            dashboard (embedded HTML, script at `/admin.js`, Tailwind CSS at `/admin.css`)
//! - `GET /healthz`     `200 ok` while the process is up (liveness, container HEALTHCHECK)
//! - `GET /readyz`      `200` only while the pipeline is streaming, else `503` (readiness)
//! - `GET /metrics`     Prometheus text exposition (also pushed over OTLP when enabled, see
//!   `telemetry.rs`)
//! - `GET /api/metrics` JSON snapshot
//! - `GET /api/events`  recent events read back from Kafka (`?topic=<t>&limit=<n>`)
//! - `GET /api/stream`  Server-Sent Events, one snapshot per second
//! - `GET /api/tables`  per table high-water marks: the newest delivered change and the
//!   topic's Kafka offsets
//! - `GET /api/routes`  the compiled route plan with live per-route counts, produced also per
//!   operation (no row data)
//! - `GET /api/routes/history` per-route outcome and per-op produced rates, and per-topic
//!   acknowledged-record rates (also per op, with totals since start) over the last 300 s (the
//!   stream carries only the newest second)
//! - `GET /api/kpis/history` the top tiles' last 300 s, one sample per second
//! - `GET|POST|DELETE /api/snapshot` state of, start, or cancel a table snapshot (ADR 0001)
//!
//! If `admin_token` is configured, `/metrics` and `/api/*` require it as
//! `Authorization: Bearer <token>`. A `?token=` query parameter is never accepted: URLs leak
//! through proxy logs, browser history and Referer. The event inspector (which exposes row
//! data) reads from the Kafka topics the sink writes to and is only enabled when a token is configured.
//!
//! Without a token (a loopback `health_addr`, or `admin_insecure_no_auth`), any web page the
//! operator visits can send requests here, so `/metrics` and `/api/*` then refuse a `Host` that is
//! a name other than `localhost` or the `health_addr` host (DNS rebinding), an `Origin` other than
//! the server's own, and a `POST` that is not `Content-Type: application/json` (a cross-site form
//! or no-cors request cannot send one).
//!
//! Defensive limits: request read timeouts (2 s for the head, 5 s for the body), a 16 KiB body cap, a cap on concurrent connections
//! with a reserve that answers only `/healthz` and `/readyz` (so a flood of idle connections cannot
//! fail the liveness probe), a cap on SSE streams, write timeouts, a timeout on inspector reads,
//! constant-time token comparison and standard security headers.

